package org.bodhnet.controller;

import com.google.gson.Gson;
import com.google.gson.JsonArray;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import com.google.gson.JsonSyntaxException;

import jakarta.servlet.AsyncContext;
import jakarta.servlet.ServletException;
import jakarta.servlet.annotation.WebServlet;
import jakarta.servlet.http.HttpServlet;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.io.PrintWriter;
import java.net.ConnectException;
import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpConnectTimeoutException;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.net.http.HttpTimeoutException;
import java.nio.charset.StandardCharsets;
import java.time.Duration;
import java.util.UUID;
import java.util.stream.Collectors;

/**
 * Controller servlet for BodhNet chat interactions — Phase 3C SSE streaming.
 *
 * Flow:
 *  1. Browser POST → this servlet (synchronous request parsing)
 *  2. Servlet starts an async context (asyncSupported = true)
 *  3. Async thread proxies the SSE stream from FastAPI to the browser
 *     by reading the response line-by-line and flushing each SSE event
 *     immediately via the HttpServletResponse output stream.
 *  4. On [DONE] or error, the async context is completed.
 *
 * The browser never waits for the full response — it receives tokens
 * as they are generated by Ollama on the local Apple Silicon device.
 */
@WebServlet(name = "ChatServlet", urlPatterns = {"/chat"}, asyncSupported = true)
public class ChatServlet extends HttpServlet {

    private static final long serialVersionUID = 2L;
    private static final String DEFAULT_AI_SERVICE_URL = "http://localhost:8000/v1/chat";

    /**
     * Async timeout for the entire stream: 3 minutes.
     * Generous to accommodate long Apple Silicon inference chains.
     */
    private static final long ASYNC_TIMEOUT_MS = 180_000L;

    private transient HttpClient httpClient;
    private transient Gson gson;
    private String aiServiceUrl;

    @Override
    public void init() throws ServletException {
        super.init();
        this.gson = new Gson();
        // Single shared HttpClient — thread-safe, reused across all requests
        this.httpClient = HttpClient.newBuilder()
                .connectTimeout(Duration.ofSeconds(10))
                .version(HttpClient.Version.HTTP_1_1)
                .build();

        String configuredUrl = System.getenv("BODHNET_AI_URL");
        if (configuredUrl == null || configuredUrl.isBlank()) {
            configuredUrl = System.getProperty("bodhnet.ai.url");
        }
        this.aiServiceUrl = (configuredUrl != null && !configuredUrl.isBlank())
                ? configuredUrl.trim()
                : DEFAULT_AI_SERVICE_URL;
    }

    // -----------------------------------------------------------------------
    // GET /chat — health / status probe (unchanged)
    // -----------------------------------------------------------------------
    @Override
    protected void doGet(HttpServletRequest request, HttpServletResponse response)
            throws ServletException, IOException {
        response.setContentType("application/json");
        response.setCharacterEncoding(StandardCharsets.UTF_8.name());

        JsonObject statusObj = new JsonObject();
        statusObj.addProperty("status", "UP");
        statusObj.addProperty("service", "BodhNet ChatServlet (SSE streaming)");
        statusObj.addProperty("target_ai_service", this.aiServiceUrl);

        try (PrintWriter out = response.getWriter()) {
            out.write(gson.toJson(statusObj));
        }
    }

    // -----------------------------------------------------------------------
    // POST /chat — SSE streaming proxy
    // -----------------------------------------------------------------------
    @Override
    protected void doPost(HttpServletRequest request, HttpServletResponse response)
            throws ServletException, IOException {

        request.setCharacterEncoding(StandardCharsets.UTF_8.name());

        // --- 1. Read and validate the incoming JSON body ------------------
        String requestBody;
        try (BufferedReader reader = request.getReader()) {
            requestBody = reader.lines().collect(Collectors.joining(System.lineSeparator()));
        }

        if (requestBody == null || requestBody.isBlank()) {
            sendJsonError(response, HttpServletResponse.SC_BAD_REQUEST, "Empty request body received");
            return;
        }

        JsonObject clientJson;
        try {
            clientJson = JsonParser.parseString(requestBody).getAsJsonObject();
        } catch (JsonSyntaxException | IllegalStateException e) {
            sendJsonError(response, HttpServletResponse.SC_BAD_REQUEST,
                    "Malformed JSON payload: " + e.getMessage());
            return;
        }

        String message = clientJson.has("message") && !clientJson.get("message").isJsonNull()
                ? clientJson.get("message").getAsString().trim()
                : "";

        if (message.isEmpty()) {
            sendJsonError(response, HttpServletResponse.SC_BAD_REQUEST, "Message content cannot be blank");
            return;
        }

        String conversationId = clientJson.has("conversation_id")
                && !clientJson.get("conversation_id").isJsonNull()
                ? clientJson.get("conversation_id").getAsString().trim()
                : UUID.randomUUID().toString();

        JsonArray history = clientJson.has("history") && clientJson.get("history").isJsonArray()
                ? clientJson.getAsJsonArray("history")
                : new JsonArray();

        // --- 2. Assemble payload for Python AI service --------------------
        JsonObject aiPayload = new JsonObject();
        aiPayload.addProperty("conversation_id", conversationId);
        aiPayload.addProperty("message", message);
        aiPayload.add("history", history);

        String payloadJson = gson.toJson(aiPayload);
        final String finalConversationId = conversationId;

        // --- 3. Configure SSE response headers BEFORE startAsync() --------
        response.setContentType("text/event-stream");
        response.setCharacterEncoding(StandardCharsets.UTF_8.name());
        response.setHeader("Cache-Control", "no-cache");
        response.setHeader("Connection", "keep-alive");
        response.setHeader("X-Conversation-Id", conversationId);
        // Disable buffering in any intermediary proxies
        response.setHeader("X-Accel-Buffering", "no");

        // --- 4. Hand off to async thread -----------------------------------
        AsyncContext asyncCtx = request.startAsync();
        asyncCtx.setTimeout(ASYNC_TIMEOUT_MS);

        asyncCtx.start(() -> {
            try {
                HttpRequest aiRequest = HttpRequest.newBuilder()
                        .uri(URI.create(aiServiceUrl))
                        .header("Content-Type", "application/json; charset=UTF-8")
                        .header("Accept", "text/event-stream")
                        .timeout(Duration.ofSeconds(150))
                        .POST(HttpRequest.BodyPublishers.ofString(payloadJson, StandardCharsets.UTF_8))
                        .build();

                // Use InputStream body handler so we can read line-by-line
                // without buffering the entire response in memory.
                HttpResponse<InputStream> aiResponse = httpClient.send(
                        aiRequest, HttpResponse.BodyHandlers.ofInputStream());

                int statusCode = aiResponse.statusCode();
                PrintWriter out = asyncCtx.getResponse().getWriter();

                if (statusCode < 200 || statusCode >= 300) {
                    // FastAPI returned an error — forward as SSE error event
                    out.write("data: [ERROR] AI service returned HTTP " + statusCode + "\n\n");
                    out.flush();
                    asyncCtx.complete();
                    return;
                }

                // Extract conversation_id from response header if FastAPI set it
                String respConvId = aiResponse.headers()
                        .firstValue("X-Conversation-Id")
                        .orElse(finalConversationId);

                // --- 5. Relay SSE lines from FastAPI → browser ---------------
                try (BufferedReader streamReader = new BufferedReader(
                        new InputStreamReader(aiResponse.body(), StandardCharsets.UTF_8))) {

                    String line;
                    while ((line = streamReader.readLine()) != null) {
                        if (line.isEmpty()) {
                            // SSE spec: blank line = event separator — forward it
                            out.write("\n");
                        } else {
                            // Forward the SSE data line verbatim (e.g. "data: token\n\n")
                            out.write(line + "\n");
                        }
                        out.flush();

                        // Detect end-of-stream sentinel from Python backend
                        if ("data: [DONE]".equals(line)) {
                            // Append conversation_id as a final metadata event
                            // so the JS client can update its state
                            out.write("\n");
                            out.write("data: [META] " + respConvId + "\n\n");
                            out.flush();
                            break;
                        }
                    }
                }

            } catch (ConnectException | HttpConnectTimeoutException e) {
                writeAsyncError(asyncCtx,
                        "Cannot connect to BodhNet AI service. Is FastAPI running on port 8000?");
            } catch (HttpTimeoutException e) {
                writeAsyncError(asyncCtx, "Stream from AI service timed out.");
            } catch (InterruptedException e) {
                Thread.currentThread().interrupt();
                writeAsyncError(asyncCtx, "Request processing was interrupted.");
            } catch (Exception e) {
                writeAsyncError(asyncCtx, "Internal streaming error: " + e.getMessage());
            } finally {
                asyncCtx.complete();
            }
        });
    }

    // -----------------------------------------------------------------------
    // Helpers
    // -----------------------------------------------------------------------

    /**
     * Writes a plain JSON error response for synchronous (pre-async) failures.
     */
    private void sendJsonError(HttpServletResponse response, int statusCode, String message)
            throws IOException {
        response.setStatus(statusCode);
        response.setContentType("application/json");
        response.setCharacterEncoding(StandardCharsets.UTF_8.name());
        JsonObject err = new JsonObject();
        err.addProperty("error", message);
        try (PrintWriter out = response.getWriter()) {
            out.write(gson.toJson(err));
        }
    }

    /**
     * Writes an SSE error event within the async context, then completes it.
     * Safe to call from the async thread — does not re-complete if already done.
     */
    private void writeAsyncError(AsyncContext asyncCtx, String message) {
        try {
            PrintWriter out = asyncCtx.getResponse().getWriter();
            out.write("data: [ERROR] " + message + "\n\n");
            out.flush();
        } catch (Exception ignored) {
            // If we can't write to the response, there's nothing more to do
        }
    }
}
